    ui.section("30 — اختبار الاستقرار المحلي لنموذج ECM عصبي مبسط", "Lab 4: local stability", "rose")
    st.markdown("لتوضيح المسألة، نفترض ثبات $X$ مؤقتًا، ونكتب:")
    st.latex(r"q_{t+1}=q_t+\alpha q_t+g_\phi(q_t).")
    st.markdown("إذا تحقق $g_\\phi(0)=0$، يكون $q=0$ نقطة ثابتة. ولكي تكون مستقرة محليًا في حالة المتغير الواحد وفق التفاضل الخطي، نحتاج:")
    st.latex(r"\boxed{|1+\alpha+g_\phi'(0)|<1.}")
    st.markdown("سنثبت مشتقة الشبكة قرب التوازن عند $g_\\phi'(0)=0.2$، ونغيّر $\\alpha$.")
    st.markdown("**مختبر 4: هل يكفي كون α سالبًا للاستقرار؟** محاكاة للمعادلة المبسطة $q(t+1)=(1+\\alpha+0.2)\\,q(t)$ مع $q(0)=1$.")
    c1, c2 = st.columns(2)
    alpha = c1.slider("معامل تعديل الخطأ α", -2.5, 0.5, -0.6, 0.05, key="f5_alpha")
    gp = c2.slider("مشتقة الشبكة عند التوازن g′(0)", -0.5, 0.8, 0.2, 0.05, key="f5_gp")
    s = 1 + alpha + gp
    stable = abs(s) < 1
    m1, m2, m3 = st.columns(3)
    m1.metric("α", f"{alpha:.2f}")
    m2.metric("معامل الانتقال الخطي 1+α+g′(0)", f"{s:.2f}")
    m3.metric("الحكم المحلي", "استقرار محلي" if stable else "لا يتحقق شرط الاستقرار")
    t = np.arange(0, 13)
    q = np.clip(s ** t, -6, 6)
    fig = go.Figure(go.Scatter(x=t, y=q, mode="lines+markers", line=dict(color="#0d9488" if stable else "#e11d48", width=3), name="q(t)"))
    fig.add_hline(y=0, line_dash="dot", line_color="#64748b")
    fig.update_xaxes(title="t")
    fig.update_yaxes(title="q(t) (مقصوص بصريًا عند ±6)", range=[-6.5, 6.5])
    ui.style_fig(fig, "مسار الانحراف عن التوازن", height=380)
    ui.show(fig)
    st.markdown(
        "جرّب: α = −0.6 مستقر (معامل 0.6). α = −1.0 يعطي 0.2، مستقر بسرعة. لكن α = −2.4 — رغم أنه **سالب** — يعطي −1.2 فيتذبذب الانحراف ويتفجر. وإن "
        "كانت $g'(0)$ موجبة بما يكفي، قد يصبح α سالب صغير غير كافٍ. **إشارة α وحدها لا تحسم الاستقرار.**"
    )
    st.caption("هذه النتيجة تتعلق بالحالة المبسطة. عند وجود عدة متغيرات أو حالات كامنة يجب تحليل مصفوفة Jacobian أو شروط استقرار مناسبة، وقد نحتاج إلى دراسة الاستقرار العالمي لا المحلي فقط.")
    st.latex(r"\text{متعدد المتغيرات:}\quad s_{t+1}=F(s_t),\qquad \rho\Big(\tfrac{\partial F}{\partial s}\big|_{s^*}\Big)<1\ \ \text{(نصف القطر الطيفي لمصفوفة جاكوبي عند التوازن)}")

