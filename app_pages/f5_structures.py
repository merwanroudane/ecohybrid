    st.markdown("حيث $u=Y-\\widehat Q_\\tau$.")
    tau = st.slider("الكمّية τ", 0.05, 0.95, 0.9, 0.05, key="f5_tau")
    u = np.linspace(-3, 3, 200)
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=u, y=np.where(u >= 0, tau * u, (tau - 1) * u), name=f"ρ_τ(u), τ = {tau:.2f}", line=dict(color="#e11d48", width=3)))
    fig.add_trace(go.Scatter(x=u, y=0.5 * u ** 2 / 3, name="مقارنة: خسارة تربيعية (مُقيَّسة)", line=dict(color="#94a3b8", dash="dot")))
    fig.update_xaxes(title="u = Y − Q̂_τ")
    fig.update_yaxes(title="الخسارة")
    ui.style_fig(fig, "خسارة Pinball غير متماثلة: τ مرتفعة تعاقب التقدير الناقص أكثر", height=360)
    ui.show(fig)
