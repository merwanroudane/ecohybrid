@st.cache_data(show_spinner="محاكاة...")
def ai_regressor_mc(kind, sigma_u, m, R=300, N=2000, seed=0):
    rng = np.random.default_rng(seed)
    delta = 0.8 if kind == "biased" else 0.0

    def slope(x, y):
        xc = x - x.mean(axis=-1, keepdims=True)
        return (xc * (y - y.mean(axis=-1, keepdims=True))).sum(-1) / (xc ** 2).sum(-1)

    g = rng.integers(0, 2, (R, N)).astype(float)          # e.g. language group, not in the regression
    s_true = rng.normal(0, 1, (R, N))                     # the construct a careful human coder would give
    y = 2.0 + 0.5 * s_true + 2.0 * g + rng.normal(0, 1, (R, N))
    s_ai = s_true + delta * g + rng.normal(0, sigma_u, (R, N))
    val = slice(0, m)                                     # a random validation sample (rows are i.i.d.)
    b_true = slope(s_true, y)
    b_ai = slope(s_ai, y)
    b_val = slope(s_true[:, val], y[:, val])
    b_ppi = b_ai - slope(s_ai[:, val], y[:, val]) + b_val
    return {"المؤشر الحقيقي لكل الوحدات (غير متاح عمليًا)": b_true, "درجات AI كأنها حقيقة (ساذج)": b_ai,
            f"عينة التحقق وحدها (m={m})": b_val, "تصحيح بعينة التحقق (PPI)": b_ppi}


