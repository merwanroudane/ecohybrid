HAWK = ["الضغوط التضخمية", "الإجراءات اللازمة", "مخاطر تضخمية", "مرتفعة", "تشديد", "نرفع", "رفع", "كبح", "تقييد"]
DOVE = ["دعم النمو", "تيسير", "تحفيز", "تباطؤ", "انخفاض", "تراجع", "نخفض", "خفض"]


def dict_score(text: str):
    found, work = [], text
    for term in sorted(HAWK + DOVE, key=len, reverse=True):
        k = work.count(term)
        if k:
            found.append((term, "تشدد" if term in HAWK else "تيسير", k))
            work = work.replace(term, " " * len(term))
    h = sum(k for _, s, k in found if s == "تشدد")
    d = sum(k for _, s, k in found if s == "تيسير")
    return (h / (h + d) if h + d else 0.5), h, d, found


