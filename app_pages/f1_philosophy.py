    st.markdown("لنقارن مثالًا خطيًا بشبكة عصبية. في الانحدار الخطي:")
    st.latex(r"\widehat Y_i=X_i^\top\beta, \qquad \widehat\beta=\arg\min_\beta\sum_{i=1}^N(Y_i-X_i^\top\beta)^2.")
    st.markdown("في الشبكة العصبية:")
    st.latex(r"\widehat Y_i=g_\phi(X_i), \qquad \widehat\phi=\arg\min_\phi\sum_{i=1}^N(Y_i-g_\phi(X_i))^2.")
    st.markdown("في الحالتين تختار عملية التقدير معلمات لتقليل خسارة معينة. لكن الشبكة مرنة لأنها تركب عمليات خطية وتحويلات غير خطية، وقد تحتوي على عدد كبير من الأوزان.")
    st.markdown("#### ما المرور الأمامي Forward Pass؟")
    st.markdown("نأخذ المدخل $X$ ونحسب طبقات الشبكة بالتتابع:")
    st.latex(r"H_1=\sigma(W_1X+b_1),\qquad H_2=\sigma(W_2H_1+b_2),\qquad \widehat Y=W_3H_2+b_3.")
    st.markdown("المدخل يمر بين الطبقات ويتحول إلى تمثيلات داخلية، إلى أن تنتج الشبكة تنبؤًا.")
    st.markdown("#### ما الانتشار العكسي Backpropagation؟")
