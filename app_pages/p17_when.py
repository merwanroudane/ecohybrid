        ("توقعات مع مؤشرات كثيرة", "اللاخطية قد تساعد", "DFM/Lasso/Boosting ثم معيار عميق"),
        ("صور أقمار وسجلات مكانية", "قياس النشاط غير المرصود", "استخراج بالرؤية + قياس مكاني"),
        ("تعميم عبر مهام عديدة", "كلفة نمذجة كل سلسلة مرتفعة", "TSFM مع تقييم آني"),
