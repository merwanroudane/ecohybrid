    @st.cache_data(show_spinner="إعادة السحب...")
    def stability(n, B=200, seed=2):
        from sklearn.linear_model import LassoCV, Lasso
        rng = np.random.default_rng(seed)
        p = 15
        cov = 0.5 ** np.abs(np.subtract.outer(np.arange(p), np.arange(p)))
        X = rng.multivariate_normal(np.zeros(p), cov, n)
        beta = np.zeros(p); beta[[0, 3, 7]] = [0.6, -0.4, 0.3]
        y = X @ beta + rng.normal(0, 1, n)
        lam = LassoCV(cv=5, random_state=0).fit(X, y).alpha_
        freq = np.zeros(p)
        for _ in range(B):
            idx = rng.integers(0, n, n)
            freq += Lasso(alpha=lam).fit(X[idx], y[idx]).coef_ != 0
        return freq / B, beta

