@st.cache_data(show_spinner="تشغيل التجربة...")
def rct_precision(n, signal, seed):
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.model_selection import KFold
    rng = np.random.default_rng(seed)
    X = rng.uniform(-2, 2, size=(n, 5))
    D = rng.integers(0, 2, n)
    base = signal * (np.sin(2 * X[:, 0]) + X[:, 1] ** 2 + 0.5 * X[:, 2] * X[:, 3])
    Y = 1.0 * D + base + rng.normal(0, 1, n)                      # true effect = 1
    # 1) difference in means
    dm = Y[D == 1].mean() - Y[D == 0].mean()
    se_dm = np.sqrt(Y[D == 1].var(ddof=1) / (D == 1).sum() + Y[D == 0].var(ddof=1) / (D == 0).sum())
    # 2) linear regression adjustment
    Z = np.column_stack([np.ones(n), D, X])
    b = np.linalg.lstsq(Z, Y, rcond=None)[0]
    r = Y - Z @ b
    V = np.linalg.inv(Z.T @ Z) * (r @ r) / (n - Z.shape[1])
    lin, se_lin = b[1], np.sqrt(V[1, 1])
    # 3) ML adjustment: cross-fitted outcome model on X only (valid because D is randomised)
    mu = np.zeros(n)
    for tr, te in KFold(5, shuffle=True, random_state=seed).split(X):
        mu[te] = RandomForestRegressor(200, min_samples_leaf=5, random_state=0, n_jobs=-1).fit(X[tr], Y[tr]).predict(X[te])
    Yt = Y - mu
    ml = Yt[D == 1].mean() - Yt[D == 0].mean()
    se_ml = np.sqrt(Yt[D == 1].var(ddof=1) / (D == 1).sum() + Yt[D == 0].var(ddof=1) / (D == 0).sum())
    return [("فرق المتوسطين (بلا تعديل)", dm, se_dm), ("تعديل بانحدار خطي", lin, se_lin), ("تعديل بغابة عشوائية + تقسيم متقاطع", ml, se_ml)]


