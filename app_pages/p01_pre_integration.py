with tabs[4]:
    ui.section("مختبر: لماذا كان «التنقيب في البيانات» تهمة؟", "Lab — spurious significance from specification search", "pink")
    st.markdown(
        "نولّد متغيرًا تابعًا $y$ **لا علاقة له إطلاقًا** بأي من $k$ متغيرات مرشحة. ثم يجرّب «الباحث» كل متغير على حدة "
        "ويُبلغ عن أي متغير دال عند 5%. شغّل الرسم المتحرك لترى كيف يقترب احتمال «اكتشاف» علاقة زائفة من 100% "
        "كلما زاد عدد المواصفات المجرَّبة — وهو بالضبط ما حذّر منه لوفيل (1983)، وما يعالجه تعلم الآلة بـ**العينة المحجوزة** و**التحقق المتقاطع**."
    )
    c1, c2 = st.columns([1, 3])
    with c1:
        n_obs = st.slider("حجم العينة n", 30, 300, 80, 10, key="dm_n")
        sims = st.slider("عدد التكرارات", 100, 600, 300, 50, key="dm_s")

    @st.cache_data(show_spinner=False)
    def data_mining_curve(n: int, reps: int) -> pd.DataFrame:
        rng = np.random.default_rng(1)
        ks = np.arange(1, 41)
        hits = np.zeros(len(ks))
        for _ in range(reps):
            y = rng.standard_normal(n)
            X = rng.standard_normal((n, ks.max()))
            yc = y - y.mean()
            Xc = X - X.mean(0)
            r = (Xc * yc[:, None]).sum(0) / np.sqrt((Xc ** 2).sum(0) * (yc ** 2).sum())
            t = r * np.sqrt((n - 2) / (1 - r ** 2))
            sig = np.abs(t) > 1.96
            hits += np.cumsum(sig) > 0
        return pd.DataFrame({"k": ks, "sim": hits / reps, "theory": 1 - 0.95 ** ks})

    d = data_mining_curve(n_obs, sims)
    fig = go.Figure(
        data=[go.Scatter(x=d.k[:1], y=d.sim[:1], mode="lines+markers", name="محاكاة",
                         line=dict(color=ui.COLORS["rose"], width=4)),
              go.Scatter(x=d.k, y=d.theory, mode="lines", name="نظري: 1 − 0.95^k",
                         line=dict(color=ui.COLORS["violet"], dash="dot"))],
        frames=[go.Frame(data=[go.Scatter(x=d.k[:i], y=d.sim[:i])], name=str(i)) for i in range(1, 41)],
    )
    fig.update_xaxes(title="عدد المواصفات/المتغيرات المجرَّبة k", range=[0, 41])
    fig.update_yaxes(title="احتمال إيجاد متغير «دال» واحد على الأقل", range=[0, 1.05], tickformat=".0%")
    ui.style_fig(fig, "التنقيب في البيانات يولّد دلالة زائفة")
    ui.add_play(fig, list(range(1, 41)), duration=160, prefix="k = ")
    with c2:
        ui.show(fig)
    ui.note("عند $k=20$ يقارب الاحتمال **64%**، وعند $k=40$ يتجاوز **87%**. الحل المعاصر: **فصل بيانات الاختيار عن بيانات التقييم** "
            "(Sample splitting)، و**تصحيح التعدد** (Multiple testing)، و**التسجيل المسبق** (Pre-registration)، و**التنظيم** (Regularization).",
            "الدرس", "pink", "💡")

