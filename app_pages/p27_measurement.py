    big_share = st.slider("حصة الشركات الكبيرة في العينة", 0.1, 0.9, 0.5, 0.05, key="stdn")

    @st.cache_data(show_spinner=False)
    def same_text(share: float, n: int = 4000, reps: int = 200):
        rng = np.random.default_rng(13)
        out = {"النموذج A (كلاسيكي)": [], "النموذج B (يرتبط بالحجم)": [], "النموذج C (يتأثر بالدورة)": [], "عينة ذهبية فقط (n=300)": []}
        for _ in range(reps):
            size = rng.binomial(1, share, n); rec = rng.binomial(1, .3, n)
            xs = rng.normal(0, 1, n) + 0.3 * rec
            inv = -0.5 * xs + 0.6 * size - 0.4 * rec + rng.normal(0, 1, n)
            xa = xs + rng.normal(0, .3, n)
            xb = xs + 0.8 * size + rng.normal(0, .4, n)
            xc = xs + 0.9 * rec + rng.normal(0, .4, n)
            for k, x in (("النموذج A (كلاسيكي)", xa), ("النموذج B (يرتبط بالحجم)", xb), ("النموذج C (يتأثر بالدورة)", xc)):
                out[k].append(np.polyfit(x, inv, 1)[0])
            g = rng.choice(n, 300, replace=False)
            out["عينة ذهبية فقط (n=300)"].append(np.polyfit(xs[g], inv[g], 1)[0])
        return {k: np.array(v) for k, v in out.items()}

