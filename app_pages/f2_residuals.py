    st.markdown("التنبؤ القياسي الأساسي يساوي 92، والقيمة الفعلية في مثالنا 100. إذن الخطأ الذي نريد أن تتعلمه الخوارزمية يساوي 8. تكون الخسارة:")
    st.latex(r"L(w)=(8-2w)^2, \qquad\frac{\partial L}{\partial w}=-4(8-2w).")
    st.markdown("**مختبر 1: خطوة Gradient Descent** — حرّك الوزن ثم نفّذ خطوة تدريب. ما الذي يحدث للتنبؤ والخسارة والتدرج؟ تجربة بمشاهدة واحدة هدفها فهم التحديث، ولا تمثل تقييمًا خارج العينة.")
    if "f2_w" not in st.session_state:
        st.session_state["f2_w"] = 1.0
    c1, c2, c3 = st.columns([3, 1, 1])
    if c2.button("▶ تحديث الوزن (η = 0.1)", key="f2_step"):
        w = st.session_state["f2_w"]
        st.session_state["f2_w"] = float(min(5.0, max(-1.0, w + 0.1 * 4 * (8 - 2 * w))))
    if c3.button("إعادة البدء", key="f2_reset"):
        st.session_state["f2_w"] = 1.0
    w = c1.slider("الوزن القابل للتعلم w", -1.0, 5.0, key="f2_w", step=0.01)
    e = 8 - 2 * w
    m1, m2, m3, m4, m5 = st.columns(5)
    m1.metric("الوزن w", f"{w:.3f}")
    m2.metric("الخطأ المتوقع 2w", f"{2 * w:.3f}")
