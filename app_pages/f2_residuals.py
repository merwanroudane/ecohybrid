with tabs[3]:
    ui.section("10 — لماذا قد تستطيع الشبكة تعلم البواقي؟ البرهان الرياضي", "Why residuals can be learned", "indigo")
    st.markdown("لنفرض أن النموذج القياسي أنتج خطأ:")
    st.latex(r"e=Y-f(X).")
    st.markdown("نريد اختيار دالة مرنة $g(Z)$ لتصحيحه عبر تقليل متوسط مربع الخطأ:")
    st.latex(r"\min_g E[(e-g(Z))^2].")
    st.markdown("النتيجة الأساسية في نظرية التنبؤ هي أن الدالة المثلى، إذا كانت المعلومات كافية وكان المعيار هو الخسارة التربيعية، هي المتوسط الشرطي:")
    st.latex(r"\boxed{g^*(Z)=E(e\mid Z).}")
    st.markdown("إذن الخوارزمية لا «تصلح أي خطأ» بطريقة سحرية، بل تبحث عن **أنماط منتظمة في الأخطاء** يمكن توقعها باستخدام $Z$.")
    st.markdown("#### مقدار التحسن النظري الممكن")
    st.markdown("باستخدام خاصية التعامد الشرطي نحصل على:")
    st.latex(r"E[e^2]=E[(e-E(e\mid Z))^2]+E[(E(e\mid Z))^2].")
    st.markdown("إذن التحسن السكاني النظري عند تصحيح التنبؤ الأساسي تصحيحًا مثاليًا هو:")
    st.latex(r"\boxed{MSE_E-MSE_{H^*}=E[(E(e\mid Z))^2].}")
    ui.note(
        "هذا البرهان بالغ الأهمية: **التحسن المحتمل لا يساوي مجموع البواقي كلها، بل الجزء القابل للتنبؤ منها**. فإذا كان المتوسط الشرطي صفرًا، فإن "
        "أفضل تصحيح للمتوسط وفق MSE هو الصفر.\n\nوقد تختلف النتيجة التجريبية لأننا لا نعرف $g^*$، بل نقدّرها بعينة محدودة؛ لذلك يمكن أن تكون الخسارة "
        "خارج العينة **أعلى** بعد الدمج.",
        "المغزى", "indigo", "📐",
    )
    with st.expander("لماذا يصح التفكيك؟ (خطوة الحد المختلط)"):
        st.markdown(
            "اكتب $e=(e-E[e\\mid Z])+E[e\\mid Z]$ وربّع. الحد المختلط $2E\\big[(e-E[e\\mid Z])\\,E[e\\mid Z]\\big]$ يساوي صفرًا بقانون التوقعات المكررة: "
            "$E\\big[E[e-E[e\\mid Z]\\mid Z]\\,E[e\\mid Z]\\big]=E[0\\cdot E[e\\mid Z]]=0$. ∎"
        )

