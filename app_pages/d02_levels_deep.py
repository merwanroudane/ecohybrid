@st.cache_data(show_spinner="تشغيل المحاكاة...")
def _dml_sim(seed: int, n: int = 1500):
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.model_selection import KFold

    rng = np.random.default_rng(seed)
    X = rng.uniform(-2, 2, size=(n, 8))
    m = np.tanh(1.5 * X[:, 0]) + 0.5 * X[:, 1] ** 2 - 0.5          # treatment depends nonlinearly on X
    g = 2.0 * np.sin(1.5 * X[:, 0]) + X[:, 1] ** 2 + 0.5 * X[:, 2] * X[:, 3]
    D = m + rng.normal(0, 1, n)
    Y = 0.5 * D + g + rng.normal(0, 1, n)

    # naive: OLS of Y on D and linear X
    Z = np.column_stack([np.ones(n), D, X])
    b, *_ = np.linalg.lstsq(Z, Y, rcond=None)
    res = Y - Z @ b
    V = np.linalg.inv(Z.T @ Z) * (res @ res) / (n - Z.shape[1])
    naive = (b[1], np.sqrt(V[1, 1]))

    # DML: cross-fitted random forests for E[Y|X] and E[D|X]
    rY, rD = np.zeros(n), np.zeros(n)
    for tr, te in KFold(5, shuffle=True, random_state=seed).split(X):
        fy = RandomForestRegressor(200, min_samples_leaf=5, n_jobs=-1, random_state=0).fit(X[tr], Y[tr])
        fd = RandomForestRegressor(200, min_samples_leaf=5, n_jobs=-1, random_state=0).fit(X[tr], D[tr])
        rY[te], rD[te] = Y[te] - fy.predict(X[te]), D[te] - fd.predict(X[te])
    th = (rD @ rY) / (rD @ rD)
    psi = (rY - th * rD) * rD
    se = np.sqrt(np.mean(psi ** 2) / np.mean(rD ** 2) ** 2 / n)
    return naive, (th, se)


def live_dml() -> None:
    st.markdown(
        "محاكاة حية: $n=1500$، ثمانية ضوابط، والأثر الحقيقي $\\theta=0.5$. المعالجة والنتيجة تعتمدان على الضوابط **بشكل لاخطي** "
        "(جيب، مربع، تفاعل). نقارن انحدارًا عاديًا بضوابط خطية مع DML بغابات عشوائية وتقسيم متقاطع خماسي:"
    )
    seed = st.number_input("بذرة المحاكاة", 0, 999, 7, key="l3_seed")
    (bn, sn), (bd, sd) = _dml_sim(int(seed))
    tab = pd.DataFrame([
        ("OLS بضوابط خطية", bn, sn, bn - 1.96 * sn, bn + 1.96 * sn),
        ("DML (غابات + تقسيم متقاطع)", bd, sd, bd - 1.96 * sd, bd + 1.96 * sd),
    ], columns=["الطريقة", "θ̂", "الخطأ المعياري", "حد أدنى 95%", "حد أعلى 95%"])
    tab["تغطي 0.5؟"] = np.where((tab["حد أدنى 95%"] <= 0.5) & (tab["حد أعلى 95%"] >= 0.5), "نعم", "لا")
    st.dataframe(tab.round(3), hide_index=True)
    st.markdown(
        "**القراءة:** الضوابط الخطية لا تلتقط الإرباك اللاخطي، فيبقى جزء منه في معامل المعالجة فيتحيز التقدير وتستبعد فترة الثقة "
        "القيمة الحقيقية غالبًا. DML يقدّر $\\mathbb E[Y\\mid X]$ و$\\mathbb E[D\\mid X]$ بمرونة ثم ينحدر **باقي النتيجة على باقي "
        "المعالجة**، فيقترب من 0.5 بفترة ثقة صحيحة. غيّر البذرة لترى أن النمط ثابت."
    )


